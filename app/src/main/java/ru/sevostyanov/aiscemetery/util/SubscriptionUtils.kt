package ru.sevostyanov.aiscemetery.util

import android.content.Context
import com.google.android.material.dialog.MaterialAlertDialogBuilder
import ru.sevostyanov.aiscemetery.user.UserManager

object SubscriptionUtils {
    
    /**
     * Показывает диалог с информацией о подписке
     * @param context контекст для показа диалога
     */
    fun showSubscriptionInfoDialog(context: Context) {
        val currentUser = UserManager.getCurrentUser()
        val hasSubscription = currentUser?.hasSubscription == true
        
        val title = if (hasSubscription) "Ваша подписка активна" else "Информация о подписке"
        
        val message = if (hasSubscription) {
            """
            🎉 У вас активная подписка!
            
            Доступные возможности:
            
            📝 Публикация мемориалов
            • Ваши мемориалы могут видеть другие пользователи
            • Размещение на общедоступной карте
            • Отправка на модерацию для публикации
            
            🌳 Генеалогические деревья
            • Создание и редактирование семейных деревьев
            • Связывание мемориалов с родственниками
            • Визуализация семейных связей
            • Публикация деревьев для других пользователей
            
            📍 Геолокация
            • Указание точного местоположения захоронения
            • Отображение на интерактивной карте
            • Навигация к месту захоронения
            
            📄 Документы
            • Загрузка документов к мемориалам
            • Хранение важных файлов
            • Доступ к архивным материалам
            
            ⭐ Приоритетная поддержка
            • Быстрое решение вопросов
            • Персональная помощь
            """.trimIndent()
        } else {
            """
            Подписка открывает множество возможностей:
            
            📝 Публикация мемориалов
            • Делитесь памятью с другими людьми
            • Ваши мемориалы станут видны всем пользователям
            • Размещение на общедоступной карте сайта
            
            🌳 Генеалогические деревья
            • Создавайте семейные деревья
            • Связывайте мемориалы с родственниками
            • Изучайте историю своей семьи
            • Публикуйте деревья для других пользователей
            • Делитесь семейной историей с сообществом
            
            📍 Геолокация и карты
            • Указывайте точное местоположение захоронений
            • Все поля местоположения разблокируются
            • Интерактивная карта с навигацией
            
            📄 Загрузка документов
            • Прикрепляйте важные документы к мемориалам
            • Сохраняйте архивные материалы
            • Делитесь историческими фотографиями
            
            ⭐ Приоритетная поддержка
            • Быстрое решение любых вопросов
            • Персональная помощь от администраторов
            
            💡 Без подписки ваши мемориалы остаются приватными и доступны только вам.
            """.trimIndent()
        }
        
        MaterialAlertDialogBuilder(context)
            .setTitle(title)
            .setMessage(message)
            .apply {
                if (hasSubscription) {
                    // Для пользователей с подпиской - только кнопка "Понятно"
                    setPositiveButton("Понятно", null)
                } else {
                    // Для пользователей без подписки - акцент на оформлении подписки
                    setPositiveButton("Оформить подписку") { _, _ ->
                        // TODO: Здесь будет переход к оформлению подписки
                        android.widget.Toast.makeText(context, "Функция оформления подписки будет добавлена в ближайшее время", android.widget.Toast.LENGTH_LONG).show()
                    }
                    setNegativeButton("Позже", null)
                }
            }
            .show()
    }
} 